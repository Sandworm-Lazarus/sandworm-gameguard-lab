const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..');
const hash=crypto.createHash('sha256').update(fs.readFileSync(path.join(root,'dist/gameguard.js'))).digest('hex');
fs.writeFileSync(path.join(root,'dist/engine-provenance.js'),'// Generated by npm run stamp; not a digital signature.\nconst GameGuardProvenance = Object.freeze('+JSON.stringify({engineVersion:'0.1.0',engineSha256:hash})+');\n');
